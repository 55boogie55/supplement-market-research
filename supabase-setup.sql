-- ORVAE: tabela independente da versão antiga FORM / LAB.
-- Executar uma vez no SQL Editor do projeto Supabase.
create extension if not exists pgcrypto;

create table if not exists public.orvae_votes (
  id bigint generated by default as identity primary key,
  submission_id uuid not null unique,
  supplement text not null check (supplement in (
    'creatina','proteina','multivitaminico','magnesio','omega_3','colagenio','vitamina_d','ashwagandha'
  )),
  flavor text not null check (flavor in (
    'mirtilo','frutos_vermelhos','laranja','limao','morango','manga','maracuja','melancia',
    'chocolate','cookie','baunilha','sem_sabor'
  )),
  created_at timestamptz not null default now()
);

alter table public.orvae_votes enable row level security;
revoke all on public.orvae_votes from public, anon, authenticated;
-- A tabela não expõe votos ao browser. A entrada pública é SOMENTE a função abaixo.

create or replace function public.submit_orvae_vote(
  p_supplement text,
  p_flavor text,
  p_submission_id uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
begin
  if p_submission_id is null or
     p_supplement is null or p_supplement not in (
       'creatina','proteina','multivitaminico','magnesio','omega_3','colagenio','vitamina_d','ashwagandha'
     ) or p_flavor is null or p_flavor not in (
       'mirtilo','frutos_vermelhos','laranja','limao','morango','manga','maracuja','melancia',
       'chocolate','cookie','baunilha','sem_sabor'
     ) then
    raise exception 'Escolha inválida' using errcode = '22023';
  end if;
  insert into public.orvae_votes(submission_id,supplement,flavor)
  values (p_submission_id,p_supplement,p_flavor)
  on conflict (submission_id) do nothing;
  return jsonb_build_object('success', true);
end;
$$;

revoke all on function public.submit_orvae_vote(text,text,uuid) from public;
grant execute on function public.submit_orvae_vote(text,text,uuid) to anon, authenticated;
notify pgrst, 'reload schema';

